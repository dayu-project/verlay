const PATTERNS: ReadonlyArray<readonly [RegExp, (...m: string[]) => string]> = [
  [
    /^Search tokens for (.+)$/,
    (_all, property) => `搜索${uiText(property)}的设计变量`,
  ],
  [/^Deselect (.+)$/, (_all, name) => `取消选择 ${name}`],
  [/^Remove (.+)$/, (_all, name) => `移除 ${name}`],
  [/^Show (.+)$/, (_all, name) => `显示${uiText(name)}`],
  [/^Hide (.+)$/, (_all, name) => `隐藏${uiText(name)}`],
  [/^Surface: (.+)$/, (_all, name) => `编辑界面：${uiText(name)}`],
  [/^Apply (\d+) changes?$/, (_all, count) => `应用 ${count} 项更改`],
  [
    /^Discard (\d+) pending changes?$/,
    (_all, count) => `放弃 ${count} 项待处理更改`,
  ],
  [/^(.+), drag to adjust$/, (_all, label) => `${uiText(label)}，拖动可调整`],
  [/^Effect type: (.+)$/, (_all, kind) => `效果类型：${uiText(kind)}`],
  [/^Actions for this (.+)$/, (_all, item) => `${uiText(item)}的操作`],
  [/^Actions for (.+)$/, (_all, item) => `${item} 的操作`],
  [/^Reorder (.+)$/, (_all, item) => `重新排序 ${item}`],
  [/^Options for (.+)$/, (_all, item) => `${item} 的选项`],
  [
    /^Coding agent: (.+), model: (.+)$/,
    (_all, agent, model) => `编程助手：${agent}，模型：${uiText(model)}`,
  ],
  [
    /^Use a design token for (.+)$/,
    (_all, property) => `为${uiText(property)}使用设计变量`,
  ],
  [
    /^Closest: (.+) \((.+)\)$/,
    (_all, name, actual) => `最接近：${name}（${actual}）`,
  ],
  [
    /^Using (.+)\. Click to change$/,
    (_all, name) => `正在使用 ${name}，点击可更换`,
  ],
  [
    /^Matches (.+)\. Click to bind$/,
    (_all, name) => `与 ${name} 匹配，点击可绑定`,
  ],
  [
    /^Stop using (.+) here and write a literal value$/,
    (_all, name) => `在此处解除 ${name}，并写入具体值`,
  ],
  [/^Not defined here · (.+)$/, (_all, where) => `未在此处定义 · ${where}`],
  [
    /^The browser picks the (.+) length$/,
    (_all, side) => `由浏览器决定${uiText(side)}长度`,
  ],
];

export function uiText(value: string): string {
  const exact = ZH_CN[value];
  if (exact) {
    return exact;
  }
  for (const [pattern, render] of PATTERNS) {
    const match = value.match(pattern);
    if (match) {
      return render(...match);
    }
  }
  return value;
}

export function isUiTextAttribute(key: string): boolean {
  return key === "aria-label" || key === "data-tip" || key === "placeholder";
}
